import { inflateSync } from 'node:zlib'
import { PDFDocument, StandardFonts } from 'pdf-lib'
import { describe, expect, it } from 'vitest'
import type { PriceListData } from '@/lib/priceList'
import { Writer } from './orderPdf'
import { buildPriceListPdf } from './priceListPdf'

/** texto desenhado no PDF: descomprime os content streams e decodifica as strings hex (<...> Tj) em WinAnsi/Latin-1 */
function drawnText(bytes: Uint8Array): string {
  const raw = Buffer.from(bytes)
  const out: string[] = []
  let i = 0
  for (;;) {
    const a = raw.indexOf('stream', i, 'latin1')
    if (a < 0) break
    let start = a + 6
    if (raw[start] === 0x0d) start++
    if (raw[start] === 0x0a) start++
    const end = raw.indexOf('endstream', start, 'latin1')
    if (end < 0) break
    try {
      out.push(inflateSync(raw.subarray(start, end)).toString('latin1'))
    } catch {
      // stream não comprimido (imagem etc.)
    }
    i = end + 9
  }
  return out
    .join('\n')
    .replace(/<([0-9A-Fa-f]+)>/g, (_, h: string) => Buffer.from(h, 'hex').toString('latin1'))
}

const data: PriceListData = {
  category: { id: 1, name: 'Categoria A' },
  incoterm: 'FOB',
  agent: null,
  generatedAt: new Date('2026-10-12T12:00:00Z'),
  groups: [{ family: 'Hidrosilo', label: '2 m', rows: [{ sku: 'HS-2M-10K', name: 'Hidrosilo 2 × 10 m', brand: 'Pacifil', widthM: 2, lengthM: 10, thicknessUm: 600, capacityL: 10000, box: null, unitsPerPallet: 26, palletCode: null, netKg: 22.37, grossKg: 28.07, priceUsd: 126, reason: null }] }],
}

describe('rodapé: quem gerou o documento', () => {
  it('lista de preços: "generado por <nome>" (es) no rodapé de cada página', async () => {
    const pdf = await buildPriceListPdf(data, { lang: 'es', generatedBy: 'Matías Teste' })
    expect(drawnText(pdf)).toContain('generado por Matías Teste')
  })

  it('rodapé com os perfis do Instagram e o link de cada um', async () => {
    const txt = drawnText(await buildPriceListPdf(data, { lang: 'es' }))
    expect(txt).toContain('Siga a Pacifil en Instagram:')
    expect(txt).toContain('@pacifil360')
    expect(txt).toContain('@pacifil.hidrosilo')
    expect(txt).toContain('https://www.instagram.com/pacifil360/')
    expect(txt).toContain('https://www.instagram.com/pacifil.hidrosilo/')
  })

  it('sem nome: nada de "gerado por"', async () => {
    const pdf = await buildPriceListPdf(data, { lang: 'pt' })
    expect(drawnText(pdf)).not.toMatch(/gerado por/i)
  })

  it('referência longa no rodapé: o nome continua aparecendo (linha de contato ou referência encurtada)', async () => {
    for (const ref of ['x'.repeat(10), 'Referência '.repeat(20), 'W'.repeat(400)]) {
      const pdf = await PDFDocument.create()
      const w = new Writer(pdf, await pdf.embedFont(StandardFonts.Helvetica), await pdf.embedFont(StandardFonts.HelveticaBold), ref, 'en')
      w.generatedBy = 'Matías Teste'
      w.finish('ref')
      expect(drawnText(await pdf.save())).toContain('generated by Matías Teste')
    }
  })
})
