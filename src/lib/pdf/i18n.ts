const DICT: Record<PdfLang, PdfText> = { pt, es, en }

export function pdfText(lang: PdfLang): PdfText {
  return DICT[lang] ?? pt
}

export function isPdfLang(v: unknown): v is PdfLang {
  return v === 'pt' || v === 'es' || v === 'en'
}

/** países de língua espanhola (ISO-2): idioma sugerido = espanhol */
const ES_COUNTRIES = new Set(['AR', 'UY', 'PY', 'CL', 'BO', 'PE', 'EC', 'CO', 'VE', 'MX', 'GT', 'HN', 'SV', 'NI', 'CR', 'PA', 'CU', 'DO', 'ES', 'PR', 'GQ'])

/**
 * Idioma sugerido pelo destino: Brasil → português; países hispânicos → espanhol; demais → inglês.
 * O país é reconhecido pelo código ISO (countryCode: código, nomes usuais e o nome de qualquer país em
 * pt/es/en — inclusive o nome canônico que o sistema grava, ex.: "Porto Rico", "Guiné Equatorial"); texto
 * livre ("Montevideo, Uruguay") cai na busca por nomes.
 */
export function defaultPdfLang(destination?: string | null): PdfLang {
  const d = (destination ?? '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
  if (!d.trim()) return 'pt'
  const code = countryCode(destination)
  if (code) return code === 'BR' ? 'pt' : ES_COUNTRIES.has(code) ? 'es' : 'en'
  if (/brasil|brazil/.test(d)) return 'pt'
  if (/argentin|uruguay|uruguai|paraguay|paraguai|chile|bolivia|peru|ecuador|equador|colombi|venezuel|mexic|guatemal|hondur|salvador|nicaragu|costa rica|panam|cuba|dominican|espan|spain|espanha|puerto rico|porto rico|guine equatorial|guinea ecuatorial|equatorial guinea/.test(d)) return 'es'
  return 'en'
}

/** Formatador numérico no idioma do PDF. */
export const numFmt = (lang: PdfLang) => {
  const loc = pdfText(lang).locale
  return (v: number, d = 0) => v.toLocaleString(loc, { minimumFractionDigits: d, maximumFractionDigits: d })
}
